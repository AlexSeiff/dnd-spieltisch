export function heroParticipant(c: Character, i = 0): Combatant {
  return {
    id: "hero-" + c.id,
    characterId: c.id,
    name: c.name,
    kind: "hero",
    hp: c.hp,
    maxHp: c.maxHp,
    tempHp: c.tempHp,
    ac: c.ac,
    initiative: 10,
    dexterity: c.stats.dexterity,
    conditions: [],
    x: 3 + i,
    y: 7,
    color: c.color,
  };
}
